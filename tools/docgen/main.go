// Command docgen writes the documentation site's generated reference data
// from the code: the configuration reference, the CLI reference and the
// example review agents. CI runs it and fails on any diff.
package main

//go:generate go run . -root ../..

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/RobertYoung/gitlab-reviewer-cli/internal/cli"
	"github.com/RobertYoung/gitlab-reviewer-cli/internal/config"
	"github.com/RobertYoung/gitlab-reviewer-cli/internal/review/agents"
)

const generatedNote = "<!-- Generated by tools/docgen from the command tree. Do not edit: run go generate ./... -->"

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()

	// Path defaults are rendered with a literal ~ so the output does not
	// depend on who runs the generator.
	for _, v := range []string{"XDG_CONFIG_HOME", "XDG_CACHE_HOME", "XDG_STATE_HOME"} {
		_ = os.Unsetenv(v)
	}
	_ = os.Setenv("HOME", "~")

	cmd := cli.New()
	cmd.InitDefaultCompletionCmd()

	outputs := map[string][]byte{}
	var err error
	if outputs["site/src/data/config-options.json"], err = configJSON(cmd); err != nil {
		log.Fatal(err)
	}
	outputs["site/src/content/docs/reference/cli.md"] = cliMarkdown(cmd)
	if outputs["site/src/data/example-agents.json"], err = exampleAgentsJSON(filepath.Join(*root, "examples", "agents")); err != nil {
		log.Fatal(err)
	}

	for path, data := range outputs {
		if bytes.ContainsRune(data, '\u2014') {
			log.Fatalf("%s: contains an em dash; reword the source text", path)
		}
		if err := os.WriteFile(filepath.Join(*root, path), data, 0o600); err != nil {
			log.Fatal(err)
		}
	}
}

type optionJSON struct {
	config.OptionDoc
	FlagType string `json:"flagType,omitempty"`
}

func configJSON(root *cobra.Command) ([]byte, error) {
	var out []optionJSON
	for _, d := range config.Reference() {
		o := optionJSON{OptionDoc: d}
		if d.Flag != "" {
			f := root.PersistentFlags().Lookup(d.Flag)
			if f == nil {
				return nil, fmt.Errorf("%s: flag --%s is not registered", d.Key, d.Flag)
			}
			o.FlagType = flagType(f)
		}
		out = append(out, o)
	}
	return marshal(out)
}

type agentJSON struct {
	File        string   `json:"file"`
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Categories  []string `json:"categories"`
	Severity    string   `json:"severity,omitempty"`
	Model       string   `json:"model,omitempty"`
	Source      string   `json:"source"`
}

func exampleAgentsJSON(dir string) ([]byte, error) {
	catalog := agents.NewCatalog(nil, []string{dir})
	if w := catalog.Warnings(); len(w) > 0 {
		return nil, fmt.Errorf("example agents: %s", strings.Join(w, "; "))
	}
	var out []agentJSON
	for _, a := range catalog.All() {
		if a.Source != agents.SourceUser {
			continue
		}
		raw, err := os.ReadFile(a.Path)
		if err != nil {
			return nil, err
		}
		cats := make([]string, len(a.Categories))
		for i, c := range a.Categories {
			cats[i] = string(c)
		}
		out = append(out, agentJSON{
			File:        filepath.Base(a.Path),
			Name:        a.Name,
			Description: a.Description,
			Categories:  cats,
			Severity:    string(a.Severity),
			Model:       a.Model,
			Source:      string(raw),
		})
	}
	slices.SortFunc(out, func(a, b agentJSON) int { return strings.Compare(a.Name, b.Name) })
	return marshal(out)
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	err := enc.Encode(v)
	return buf.Bytes(), err
}

func flagType(f *pflag.Flag) string {
	switch f.Value.Type() {
	case "stringArray":
		return "repeatable"
	case "stringSlice":
		return "comma-separated, repeatable"
	case "float64":
		return "number"
	case "int":
		return "integer"
	case "bool":
		return "boolean"
	}
	return f.Value.Type()
}

func cliMarkdown(root *cobra.Command) []byte {
	var b strings.Builder
	b.WriteString("---\ntitle: CLI reference\ndescription: Every gitlab-reviewer command and its flags, generated from the command tree.\n---\n\n")
	b.WriteString(generatedNote + "\n\n")
	b.WriteString("This page is generated from the CLI's command tree, so it always matches the binary built from the same commit. Every configuration setting is also a [global flag](#global-flags) accepted by every command; the [configuration reference](../configuration/) maps each flag to its settings-file key and environment variable.\n\n")

	cmds := commands(root)
	b.WriteString("| Command | Description |\n|---|---|\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", c.CommandPath(), anchor(c.CommandPath()), cell(c.Short))
	}
	b.WriteString("\n")

	for _, c := range cmds {
		fmt.Fprintf(&b, "## %s\n\n", c.CommandPath())
		fmt.Fprintf(&b, "%s.\n\n", strings.TrimSuffix(prose(c.Short), "."))
		if c.Runnable() {
			fmt.Fprintf(&b, "```sh\n%s\n```\n\n", c.UseLine())
		}
		if c.Long != "" && c.Long != c.Short {
			b.WriteString(paragraphs(c.Long, c.Short))
		}
		if subs := visibleSubcommands(c); len(subs) > 0 {
			b.WriteString("Subcommands:\n\n")
			for _, s := range subs {
				fmt.Fprintf(&b, "- [`%s`](#%s): %s\n", s.Name(), anchor(s.CommandPath()), prose(s.Short))
			}
			b.WriteString("\n")
		}
		if local := visibleFlags(c.LocalNonPersistentFlags()); len(local) > 0 {
			b.WriteString("| Flag | Type | Default | Description |\n|---|---|---|---|\n")
			for _, f := range local {
				fmt.Fprintf(&b, "| `--%s` | %s | %s | %s |\n", f.Name, flagType(f), defaultCell(f), cell(f.Usage))
			}
			b.WriteString("\n")
		}
	}

	keyFor := map[string]string{}
	for _, d := range config.Reference() {
		if d.Flag != "" {
			keyFor[d.Flag] = d.Key
		}
	}
	b.WriteString("## Global flags\n\nAccepted by every command. Each one sets the configuration key in the second column, with the precedence flags, then environment, then settings file, then defaults.\n\n")
	b.WriteString("| Flag | Setting | Type | Description |\n|---|---|---|---|\n")
	for _, f := range visibleFlags(root.PersistentFlags()) {
		setting := "n/a"
		if key, ok := keyFor[f.Name]; ok {
			setting = fmt.Sprintf("[`%s`](../configuration/#%s)", key, key)
		}
		fmt.Fprintf(&b, "| `--%s` | %s | %s | %s |\n", f.Name, setting, flagType(f), cell(f.Usage))
	}
	return []byte(b.String())
}

func commands(c *cobra.Command) []*cobra.Command {
	out := []*cobra.Command{c}
	for _, s := range visibleSubcommands(c) {
		out = append(out, commands(s)...)
	}
	return out
}

func visibleSubcommands(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() && s.Name() != "help" {
			out = append(out, s)
		}
	}
	return out
}

func visibleFlags(fs *pflag.FlagSet) []*pflag.Flag {
	var out []*pflag.Flag
	fs.VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Deprecated == "" && f.Name != "help" {
			out = append(out, f)
		}
	})
	return out
}

func defaultCell(f *pflag.Flag) string {
	switch f.DefValue {
	case "", "[]", "0", "false":
		return ""
	}
	return "`" + f.DefValue + "`"
}

func anchor(path string) string { return strings.ReplaceAll(path, " ", "-") }

// paragraphs renders cobra's hard-wrapped help text: wrapped lines are
// joined, and indented blocks (shell examples) become code blocks. A
// leading paragraph that repeats the short description is dropped.
func paragraphs(long, short string) string {
	var b strings.Builder
	for i, p := range strings.Split(strings.TrimSpace(long), "\n\n") {
		if i == 0 && strings.TrimSuffix(strings.TrimSpace(p), ".") == strings.TrimSuffix(short, ".") {
			continue
		}
		lines := strings.Split(p, "\n")
		if strings.HasPrefix(lines[0], " ") || strings.HasPrefix(lines[0], "\t") {
			fmt.Fprintf(&b, "```sh\n%s\n```\n\n", strings.TrimRight(dedent(lines), "\n"))
			continue
		}
		b.WriteString(prose(strings.Join(lines, " ")) + "\n\n")
	}
	return b.String()
}

func dedent(lines []string) string {
	indent := len(lines[0]) - len(strings.TrimLeft(lines[0], " \t"))
	for i, l := range lines {
		if len(l) >= indent {
			lines[i] = l[indent:]
		}
	}
	return strings.Join(lines, "\n")
}

var proseEscaper = strings.NewReplacer("<", "&lt;", ">", "&gt;", "*", "\\*")

func prose(s string) string { return proseEscaper.Replace(s) }

func cell(s string) string { return strings.ReplaceAll(prose(s), "|", "\\|") }
